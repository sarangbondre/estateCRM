// Generates infra/supabase/migrations/20260927000100_platform_schedules.sql (F-15, CR-008) from infra/schedules.yaml,
// contracts/generated/event-topology.json and the contracts' /internal/v1/{relay,drain,jobs} endpoints:
//   - platform.service_endpoints (base URL + enabled flag per service; set per environment, never in git)
//   - platform.invoke(service, path): pg_net POST with the service's X-Cron-Secret from Supabase Vault
//   - pg_cron jobs: relay + every drain queue each minute, and every scheduled job from the catalogue
//   - platform.check_alarms(): DLQ depth, relay lag, queue lag, failed jobs / scheduler calls → platform.alarm_events,
//     optional webhook (Vault secret `alarm_webhook_url`)
import { readFileSync, writeFileSync } from 'node:fs';
import { load } from 'js-yaml';
import { root } from './contracts/events.mjs';

const catalogue = load(readFileSync(new URL('infra/schedules.yaml', root), 'utf8'));
const topology = JSON.parse(readFileSync(new URL('contracts/generated/event-topology.json', root), 'utf8'));
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
const CRON = /^(\S+\s+){4}\S+$/;

const problems = [];
const jobs = []; // { name, schedule, service, path }
for (const [svc, t] of Object.entries(topology.services)) {
  const spec = JSON.parse(readFileSync(new URL(`contracts/generated/openapi/${svc}.json`, root), 'utf8'));
  if (!spec.paths['/internal/v1/relay']?.post)
    problems.push(`${svc}: no POST /internal/v1/relay in the contract`);
  jobs.push({
    name: `estatecrm:${svc}:relay`,
    schedule: '* * * * *',
    service: svc,
    path: '/internal/v1/relay',
  });
  for (const q of [t.eventQueue, ...t.workQueues]) {
    jobs.push({
      name: `estatecrm:${svc}:drain:${q}`,
      schedule: '* * * * *',
      service: svc,
      path: `/internal/v1/drain/${q}`,
    });
  }
  const jobParam = spec.paths['/internal/v1/jobs/{name}']?.post?.parameters?.find((p) => p.name === 'name');
  const contractJobs = jobParam?.schema?.enum ?? [];
  const listed = catalogue.jobs?.[svc] ?? {};
  for (const j of contractJobs)
    if (!(j in listed)) problems.push(`${svc}: job ${j} is in the contract but not in infra/schedules.yaml`);
  for (const [j, schedule] of Object.entries(listed)) {
    if (!contractJobs.includes(j))
      problems.push(`${svc}: job ${j} is in infra/schedules.yaml but not in the contract`);
    if (schedule === 'on-demand') continue;
    if (!CRON.test(schedule)) problems.push(`${svc}: job ${j} has an invalid cron schedule "${schedule}"`);
    jobs.push({ name: `estatecrm:${svc}:job:${j}`, schedule, service: svc, path: `/internal/v1/jobs/${j}` });
  }
}
if (problems.length) {
  process.stderr.write(`${problems.join('\n')}\n`);
  process.exit(1);
}

const a = catalogue.alarms;
const queueOwners = Object.entries(topology.services).flatMap(([svc, t]) =>
  [t.eventQueue, ...t.workQueues].map((q) => [q, svc]),
);
const out = [];
const w = (s = '') => out.push(s);

w('-- GENERATED by tools/gen-schedules.mjs from infra/schedules.yaml + contracts. Do not edit; regenerate.');
w('-- Schedules and in-database alarms (F-15, ADR-0003, CR-008). Idempotent: safe to re-run.');
w('-- Per-environment values are NOT here: base URLs/enabled flags (platform.service_endpoints) and secrets');
w(
  '-- (Vault: cron_secret_<schema>, alarm_webhook_url) are set by infra/scripts (local) or the provisioning runbook.',
);
w();
w('create schema if not exists platform;');
w('revoke all on schema platform from public, anon, authenticated;');
w();
w(`create table if not exists platform.service_endpoints (
  service text primary key,
  base_url text,
  enabled boolean not null default false,
  updated_at timestamptz not null default now()
);`);
w(
  `insert into platform.service_endpoints (service) values ${Object.keys(topology.services)
    .map((s) => `(${lit(s)})`)
    .join(', ')} on conflict do nothing;`,
);
w();
w(`create table if not exists platform.queue_owners (queue text primary key, service text not null);`);
w('truncate platform.queue_owners;');
w(
  `insert into platform.queue_owners (queue, service) values ${queueOwners.map(([q, s]) => `(${lit(q)}, ${lit(s)})`).join(', ')};`,
);
w();
w(`create table if not exists platform.invocations (
  request_id bigint primary key,
  service text not null,
  path text not null,
  invoked_at timestamptz not null default now()
);
create index if not exists invocations_invoked_at on platform.invocations (invoked_at);`);
w();
w(`create table if not exists platform.alarm_events (
  id bigserial primary key,
  alarm text not null,
  service text not null,
  subject text not null,
  value numeric,
  threshold numeric,
  status text not null default 'firing' check (status in ('firing', 'resolved')),
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  resolved_at timestamptz,
  notified_at timestamptz,
  resolved_notified_at timestamptz
);
create unique index if not exists alarm_events_firing on platform.alarm_events (alarm, service, subject) where status = 'firing';
create index if not exists alarm_events_status on platform.alarm_events (status, last_seen_at);`);
w();
w(`-- One scheduler call. No-op (null) when the service isn't enabled in this environment or has no secret.
create or replace function platform.invoke(p_service text, p_path text) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_url text;
  v_secret text;
  v_id bigint;
begin
  select base_url into v_url from platform.service_endpoints where service = p_service and enabled and base_url is not null;
  if v_url is null then return null; end if;
  select decrypted_secret into v_secret from vault.decrypted_secrets where name = 'cron_secret_' || replace(p_service, '-', '_');
  if v_secret is null then
    raise warning 'platform.invoke: no cron secret for %', p_service;
    return null;
  end if;
  select net.http_post(
    url := rtrim(v_url, '/') || p_path,
    body := '{}'::jsonb,
    headers := jsonb_build_object('Content-Type', 'application/json', 'X-Cron-Secret', v_secret, 'X-Correlation-Id', 'cron-' || gen_random_uuid()),
    timeout_milliseconds := 60000
  ) into v_id;
  insert into platform.invocations (request_id, service, path) values (v_id, p_service, p_path) on conflict do nothing;
  return v_id;
end $$;
revoke all on function platform.invoke(text, text) from public, anon, authenticated;`);
w();
w(`create or replace function platform.raise_alarm(p_alarm text, p_service text, p_subject text, p_value numeric, p_threshold numeric)
returns void language sql security definer set search_path = '' as $$
  insert into platform.alarm_events (alarm, service, subject, value, threshold)
  values (p_alarm, p_service, p_subject, p_value, p_threshold)
  on conflict (alarm, service, subject) where status = 'firing'
  do update set last_seen_at = now(), value = excluded.value
$$;`);
w();
w(`-- Evaluated every minute. Payloads carry service/queue/job names and numbers only (no PII).
create or replace function platform.check_alarms() returns integer
language plpgsql security definer set search_path = '' as $$
declare
  v_started timestamptz := now(); -- alarms seen in this run get last_seen_at = now() (same transaction)
  v_window interval := make_interval(mins => ${Number(a['job-failure-window-min'])});
  r record;
  v_lag numeric;
  v_webhook text;
  v_env text;
  v_firing integer;
begin
  -- DLQ depth
  for r in
    select m.queue_name, m.queue_length, coalesce(o.service, 'platform') as service
    from pgmq.metrics_all() m left join platform.queue_owners o on o.queue = left(m.queue_name, length(m.queue_name) - 4)
    where m.queue_name like '%\\_dlq' and m.queue_length > ${Number(a['dlq-depth'])}
  loop
    perform platform.raise_alarm('dlq-depth', r.service, r.queue_name, r.queue_length, ${Number(a['dlq-depth'])});
  end loop;

  -- Queue lag (oldest visible-or-not message) on event and work queues
  for r in
    select m.queue_name, m.oldest_msg_age_sec, o.service
    from pgmq.metrics_all() m join platform.queue_owners o on o.queue = m.queue_name
    where m.oldest_msg_age_sec > ${Number(a['queue-lag-sec'])}
  loop
    perform platform.raise_alarm('queue-lag', r.service, r.queue_name, r.oldest_msg_age_sec, ${Number(a['queue-lag-sec'])});
  end loop;

  -- Relay lag: oldest unpublished outbox row per service (uses the partial index on published_at is null)
  for r in select service, replace(service, '-', '_') as schema from platform.service_endpoints loop
    if to_regclass(r.schema || '.outbox') is not null then
      execute format('select extract(epoch from now() - min(occurred_at)) from %I.outbox where published_at is null', r.schema) into v_lag;
      if v_lag > ${Number(a['relay-lag-sec'])} then
        perform platform.raise_alarm('relay-lag', r.service, 'outbox', round(v_lag), ${Number(a['relay-lag-sec'])});
      end if;
    end if;
  end loop;

  -- Failed pg_cron runs
  for r in
    select j.jobname, count(*) as n
    from cron.job_run_details d join cron.job j on j.jobid = d.jobid
    where d.status = 'failed' and d.start_time > now() - v_window and j.jobname like 'estatecrm:%'
    group by j.jobname
  loop
    perform platform.raise_alarm('job-failed', split_part(r.jobname, ':', 2), r.jobname, r.n, 0);
  end loop;

  -- Scheduler calls that failed, timed out or got a 4xx/5xx from the service
  for r in
    select i.service, i.path, count(*) as n
    from platform.invocations i join net._http_response h on h.id = i.request_id
    where i.invoked_at > now() - v_window and (h.timed_out or h.error_msg is not null or h.status_code >= 400)
    group by i.service, i.path
  loop
    perform platform.raise_alarm('invoke-failed', r.service, r.path, r.n, 0);
  end loop;

  -- Anything not seen in this run is resolved
  update platform.alarm_events set status = 'resolved', resolved_at = now()
  where status = 'firing' and last_seen_at < v_started;

  -- Optional webhook (Vault: alarm_webhook_url); one message per state change
  select decrypted_secret into v_webhook from vault.decrypted_secrets where name = 'alarm_webhook_url';
  if v_webhook is not null then
    select coalesce((select decrypted_secret from vault.decrypted_secrets where name = 'environment_name'), 'unknown') into v_env;
    for r in select * from platform.alarm_events where status = 'firing' and notified_at is null loop
      perform net.http_post(url := v_webhook, body := jsonb_build_object('environment', v_env, 'state', 'firing', 'alarm', r.alarm,
        'service', r.service, 'subject', r.subject, 'value', r.value, 'threshold', r.threshold, 'since', r.first_seen_at));
      update platform.alarm_events set notified_at = now() where id = r.id;
    end loop;
    for r in select * from platform.alarm_events where status = 'resolved' and notified_at is not null and resolved_notified_at is null loop
      perform net.http_post(url := v_webhook, body := jsonb_build_object('environment', v_env, 'state', 'resolved', 'alarm', r.alarm,
        'service', r.service, 'subject', r.subject, 'since', r.first_seen_at, 'resolvedAt', r.resolved_at));
      update platform.alarm_events set resolved_notified_at = now() where id = r.id;
    end loop;
  end if;

  select count(*) into v_firing from platform.alarm_events where status = 'firing';
  return v_firing;
end $$;
revoke all on function platform.check_alarms() from public, anon, authenticated;
revoke all on function platform.raise_alarm(text, text, text, numeric, numeric) from public, anon, authenticated;`);
w();
w(`create or replace function platform.prune() returns void
language sql security definer set search_path = '' as $$
  delete from platform.invocations where invoked_at < now() - interval '2 days';
  delete from platform.alarm_events where status = 'resolved' and resolved_at < now() - interval '30 days';
  delete from cron.job_run_details where end_time < now() - interval '7 days';
$$;`);
w();
w(
  '-- pg_cron jobs (cron.schedule with an existing name updates it). Jobs no longer in the catalogue are removed.',
);
const allNames = [...jobs.map((j) => j.name), 'estatecrm:platform:alarms', 'estatecrm:platform:prune'];
w(
  `select cron.unschedule(jobid) from cron.job where jobname like 'estatecrm:%' and jobname <> all (array[${allNames.map(lit).join(', ')}]::text[]);`,
);
for (const j of jobs) {
  w(
    `select cron.schedule(${lit(j.name)}, ${lit(j.schedule)}, ${lit(`select platform.invoke(${lit(j.service)}, ${lit(j.path)})`)});`,
  );
}
w(`select cron.schedule('estatecrm:platform:alarms', '* * * * *', 'select platform.check_alarms()');`);
w(`select cron.schedule('estatecrm:platform:prune', '40 * * * *', 'select platform.prune()');`);
w();

writeFileSync(
  new URL('infra/supabase/migrations/20260927000100_platform_schedules.sql', root),
  `${out.join('\n')}\n`,
);
process.stdout.write(`schedules: ${jobs.length} scheduler calls + 2 platform jobs\n`);
