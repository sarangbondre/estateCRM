// Generates the platform bootstrap (F-06, data-hosting §2–3, ADR-0003/0006) from the contracts:
//   - infra/supabase/migrations/20260927000000_platform_bootstrap.sql: per-service schema + roles, extensions, pgmq queues
//     (one event queue per consumer + each service's private work queues, all with DLQs) and SECURITY DEFINER queue
//     wrappers. A service may send only to the consumers of the events it produces and to its own queues, and may
//     read/ack only its own queues (and their DLQs).
//   - contracts/generated/event-topology.json: the same routing as data, for each service's relay and drains.
// Sources: contracts/asyncapi/events.yaml (producers/consumers) and the `/internal/v1/drain/{queue}` enums in
// contracts/openapi/<service>.yaml (work queues). Regenerate with `pnpm contracts:gen`.
import { readFileSync, writeFileSync } from 'node:fs';
import { load } from 'js-yaml';
import { events, queueOf, root } from './contracts/events.mjs';

// Pilot connection caps (data-hosting §5). Production caps are applied at provisioning.
const SERVICES = {
  web: 3,
  intake: 5,
  records: 6,
  journeys: 4,
  'crm-engine': 4,
  listings: 4,
  insight: 3,
};
const schemaOf = (svc) => svc.replaceAll('-', '_');
const lit = (s) => `'${s.replaceAll("'", "''")}'`;
const arr = (xs) => `array[${xs.map(lit).join(', ')}]::text[]`;

const all = events();
for (const c of new Set(all.flatMap((e) => e.consumers))) {
  if (!(c in SERVICES)) throw new Error(`consumer ${c} is not a known service`);
}

const drainQueues = (svc) => {
  const spec = load(readFileSync(new URL(`contracts/openapi/${svc}.yaml`, root), 'utf8'));
  const params = spec.paths['/internal/v1/drain/{queue}']?.post?.parameters ?? [];
  return params.find((p) => p.name === 'queue')?.schema?.enum ?? [];
};

const topology = { services: {}, routes: {} };
for (const svc of Object.keys(SERVICES)) {
  const eventQueue = queueOf(svc);
  const drains = drainQueues(svc);
  if (!drains.includes(eventQueue))
    throw new Error(`${svc}: drain enum must include its event queue ${eventQueue}`);
  const workQueues = drains.filter((q) => q !== eventQueue).sort();
  const produced = all.filter((e) => e.producer === svc || e.producer === '*');
  const sendsTo = [...new Set(produced.flatMap((e) => e.consumers))].map(queueOf).sort();
  topology.services[svc] = { schema: schemaOf(svc), eventQueue, workQueues, sendsTo };
}
for (const e of all)
  topology.routes[e.type] = { producer: e.producer, queues: e.consumers.map(queueOf).sort() };

const owned = (svc) => {
  const t = topology.services[svc];
  const base = [t.eventQueue, ...t.workQueues];
  return { base, withDlq: [...base, ...base.map((q) => `${q}_dlq`)] };
};

const out = [];
const w = (s = '') => out.push(s);

w(
  '-- GENERATED by tools/gen-db-bootstrap.mjs from contracts/asyncapi/events.yaml + contracts/openapi. Do not edit.',
);
w(
  '-- Platform bootstrap (F-06): data-hosting §2–3, ADR-0003 (pgmq transport), ADR-0006 (schema + role per service).',
);
w(
  '-- Idempotent: roles are cluster-wide and survive `supabase db reset`, so every statement tolerates re-runs.',
);
w(
  '-- Passwords are never set here. Local: infra/scripts/local-roles.mjs. Pilot/production: provisioning runbook.',
);
w();
w(
  '-- Extensions ----------------------------------------------------------------------------------------------',
);
w('create extension if not exists pgmq;');
w('create extension if not exists pg_cron;');
w('create extension if not exists pg_net with schema extensions;');
w();
w(
  '-- Hardening --------------------------------------------------------------------------------------------------',
);
w('revoke create on schema public from public;');
w();
w('do $$');
w('begin');
w("  if not exists (select 1 from pg_roles where rolname = 'relay_invoker') then");
w('    create role relay_invoker nologin;');
w('  end if;');
w('end $$;');
w('grant usage on schema net to relay_invoker;');
w('grant execute on function net.http_post(text, jsonb, jsonb, jsonb, integer) to relay_invoker;');
w();

for (const [svc, cap] of Object.entries(SERVICES)) {
  const s = schemaOf(svc);
  w(`-- ${svc} ${'-'.repeat(100 - svc.length)}`);
  w('do $$');
  w('begin');
  w(
    `  if not exists (select 1 from pg_roles where rolname = '${s}_owner') then create role ${s}_owner nologin; end if;`,
  );
  w(
    `  if not exists (select 1 from pg_roles where rolname = '${s}_migrator') then create role ${s}_migrator login noinherit; end if;`,
  );
  w(
    `  if not exists (select 1 from pg_roles where rolname = '${s}_svc') then create role ${s}_svc login; end if;`,
  );
  // PG16+: the bootstrap role needs membership to create the schema for the owner and set its default privileges.
  w(`  execute format('grant ${s}_owner to %I', current_user);`);
  w('end $$;');
  w(`alter role ${s}_svc connection limit ${cap};`);
  w(`alter role ${s}_migrator connection limit 2;`);
  w(`grant ${s}_owner to ${s}_migrator;`);
  w(`create schema if not exists ${s} authorization ${s}_owner;`);
  w(`revoke all on schema ${s} from public, anon, authenticated;`);
  w(`grant usage on schema ${s} to ${s}_svc;`);
  w(
    `alter default privileges for role ${s}_owner in schema ${s} grant select, insert, update, delete on tables to ${s}_svc;`,
  );
  w(
    `alter default privileges for role ${s}_owner in schema ${s} grant usage, select on sequences to ${s}_svc;`,
  );
  w(`alter default privileges for role ${s}_owner in schema ${s} grant execute on functions to ${s}_svc;`);
  w(`alter role ${s}_svc set search_path = ${s};`);
  w(`alter role ${s}_migrator set search_path = ${s};`);
  w(`alter role ${s}_migrator set role = ${s}_owner;`);
  w();
}

w(
  '-- Queues: event queue per consumer + private work queues, each with a DLQ (conventions §5) --------------------',
);
for (const svc of Object.keys(SERVICES)) {
  for (const q of owned(svc).withDlq) {
    w(
      `select pgmq.create(${lit(q)}) where not exists (select 1 from pgmq.list_queues() where queue_name = ${lit(q)});`,
    );
  }
}
w();

w(
  '-- Queue wrappers: the only way service roles touch pgmq (data-hosting §3). ---------------------------------',
);
w("-- Owned by the bootstrap role (SECURITY DEFINER), executable only by that service's runtime role.");
for (const svc of Object.keys(SERVICES)) {
  const s = schemaOf(svc);
  const t = topology.services[svc];
  const { base, withDlq } = owned(svc);
  const sendable = [...new Set([...t.sendsTo, ...withDlq])].sort();
  const guard = (list, what) => [
    `  if not (p_queue = any (${arr(list)})) then`,
    `    raise exception 'queue % is not ${what} ${svc}', p_queue using errcode = '42501';`,
    '  end if;',
  ];
  w();
  w(`-- ${svc}: owns ${base.join(', ')} (+ DLQs); sends to ${t.sendsTo.join(', ') || '(no consumers)'}`);
  const fn = (sig, returns, lang, body) => {
    w(`create or replace function ${s}.${sig} returns ${returns}`);
    w(`language ${lang} security definer set search_path = '' as $$`);
    body.forEach((l) => w(l));
    w('$$;');
  };
  fn('queue_send(p_queue text, p_msg jsonb, p_delay integer default 0)', 'bigint', 'plpgsql', [
    'declare v_id bigint;',
    'begin',
    ...guard(sendable, 'a queue writable by'),
    '  select * into v_id from pgmq.send(p_queue, p_msg, p_delay);',
    '  return v_id;',
    'end',
  ]);
  fn('queue_read(p_queue text, p_vt integer, p_qty integer)', 'setof pgmq.message_record', 'plpgsql', [
    'begin',
    ...guard(withDlq, 'owned by'),
    '  return query select * from pgmq.read(p_queue, p_vt, p_qty);',
    'end',
  ]);
  fn('queue_set_vt(p_queue text, p_msg_id bigint, p_vt_offset integer)', 'void', 'plpgsql', [
    'begin',
    ...guard(withDlq, 'owned by'),
    '  perform pgmq.set_vt(p_queue, p_msg_id, p_vt_offset);',
    'end',
  ]);
  fn('queue_delete(p_queue text, p_msg_id bigint)', 'boolean', 'plpgsql', [
    'begin',
    ...guard(withDlq, 'owned by'),
    '  return pgmq.delete(p_queue, p_msg_id);',
    'end',
  ]);
  fn('queue_archive(p_queue text, p_msg_id bigint)', 'boolean', 'plpgsql', [
    'begin',
    ...guard(withDlq, 'owned by'),
    '  return pgmq.archive(p_queue, p_msg_id);',
    'end',
  ]);
  fn(
    'queue_depths(out queue_name text, out queue_length bigint, out oldest_msg_age_sec integer)',
    'setof record',
    'sql',
    [
      `  select m.queue_name, m.queue_length, m.oldest_msg_age_sec from pgmq.metrics_all() m where m.queue_name = any (${arr(withDlq)})`,
    ],
  );
  for (const f of [
    'queue_send(text, jsonb, integer)',
    'queue_read(text, integer, integer)',
    'queue_set_vt(text, bigint, integer)',
    'queue_delete(text, bigint)',
    'queue_archive(text, bigint)',
    'queue_depths()',
  ]) {
    w(`revoke all on function ${s}.${f} from public, anon, authenticated;`);
    w(`grant execute on function ${s}.${f} to ${s}_svc;`);
  }
}
w();

writeFileSync(
  new URL('infra/supabase/migrations/20260927000000_platform_bootstrap.sql', root),
  `${out.join('\n')}\n`,
);
writeFileSync(
  new URL('contracts/generated/event-topology.json', root),
  `${JSON.stringify(topology, null, 2)}\n`,
);
const queueCount = Object.keys(SERVICES).reduce((n, svc) => n + owned(svc).withDlq.length, 0);
process.stdout.write(
  `db bootstrap: ${Object.keys(SERVICES).length} services, ${queueCount} queues; event-topology.json\n`,
);
