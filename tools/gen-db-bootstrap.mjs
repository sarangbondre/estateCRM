// Generates the platform bootstrap migration (F-06, data-hosting §2–3, ADR-0003/0006) from the AsyncAPI contract:
// per-service schema + roles, extensions, per-consumer pgmq queues + DLQs, and SECURITY DEFINER queue wrappers
// that limit each service to sending to the consumers of the events it produces, and reading its own queue only.
// Output: infra/supabase/migrations/20260927000000_platform_bootstrap.sql. Regenerate with `pnpm contracts:gen`.
import { writeFileSync } from 'node:fs';
import { events, queueOf, root } from './contracts/events.mjs';

// Pilot connection caps (data-hosting §5). Production caps are applied at provisioning.
const SERVICES = {
  web: 3,
  intake: 5,
  records: 6,
  journeys: 4,
  'crm-engine': 4,
  listings: 4,
  insight: 3,
};
const schemaOf = (svc) => svc.replaceAll('-', '_');
const lit = (s) => `'${s.replaceAll("'", "''")}'`;

const all = events();
const consumers = [...new Set(all.flatMap((e) => e.consumers))].sort();
const sendTargets = Object.fromEntries(
  Object.keys(SERVICES).map((svc) => [
    svc,
    [...new Set(all.filter((e) => e.producer === svc || e.producer === '*').flatMap((e) => e.consumers))]
      .map(queueOf)
      .sort(),
  ]),
);
for (const c of consumers) {
  if (!(c in SERVICES)) throw new Error(`consumer ${c} is not a known service`);
}

const out = [];
const w = (s = '') => out.push(s);

w('-- GENERATED by tools/gen-db-bootstrap.mjs from contracts/asyncapi/events.yaml. Do not edit; regenerate.');
w(
  '-- Platform bootstrap (F-06): data-hosting §2–3, ADR-0003 (pgmq transport), ADR-0006 (schema + role per service).',
);
w(
  '-- Idempotent: roles are cluster-wide and survive `supabase db reset`, so every statement tolerates re-runs.',
);
w(
  '-- Passwords are never set here. Local: infra/scripts/local-roles.mjs. Pilot/production: provisioning runbook.',
);
w();
w(
  '-- Extensions ----------------------------------------------------------------------------------------------',
);
w('create extension if not exists pgmq;');
w('create extension if not exists pg_cron;');
w('create extension if not exists pg_net with schema extensions;');
w();
w(
  '-- Hardening --------------------------------------------------------------------------------------------------',
);
w('revoke create on schema public from public;');
w();
w('do $$');
w('begin');
w("  if not exists (select 1 from pg_roles where rolname = 'relay_invoker') then");
w('    create role relay_invoker nologin;');
w('  end if;');
w('end $$;');
w('grant usage on schema net to relay_invoker;');
w('grant execute on function net.http_post(text, jsonb, jsonb, jsonb, integer) to relay_invoker;');
w();

for (const [svc, cap] of Object.entries(SERVICES)) {
  const s = schemaOf(svc);
  w(`-- ${svc} ${'-'.repeat(100 - svc.length)}`);
  w('do $$');
  w('begin');
  w(
    `  if not exists (select 1 from pg_roles where rolname = '${s}_owner') then create role ${s}_owner nologin; end if;`,
  );
  w(
    `  if not exists (select 1 from pg_roles where rolname = '${s}_migrator') then create role ${s}_migrator login noinherit; end if;`,
  );
  w(
    `  if not exists (select 1 from pg_roles where rolname = '${s}_svc') then create role ${s}_svc login; end if;`,
  );
  // PG16+: the bootstrap role needs membership to own-create the schema and set default privileges for the owner.
  w(`  execute format('grant ${s}_owner to %I', current_user);`);
  w('end $$;');
  w(`alter role ${s}_svc connection limit ${cap};`);
  w(`alter role ${s}_migrator connection limit 2;`);
  w(`grant ${s}_owner to ${s}_migrator;`);
  w(`create schema if not exists ${s} authorization ${s}_owner;`);
  w(`revoke all on schema ${s} from public, anon, authenticated;`);
  w(`grant usage on schema ${s} to ${s}_svc;`);
  w(
    `alter default privileges for role ${s}_owner in schema ${s} grant select, insert, update, delete on tables to ${s}_svc;`,
  );
  w(
    `alter default privileges for role ${s}_owner in schema ${s} grant usage, select on sequences to ${s}_svc;`,
  );
  w(`alter default privileges for role ${s}_owner in schema ${s} grant execute on functions to ${s}_svc;`);
  w(`alter role ${s}_svc set search_path = ${s};`);
  w(`alter role ${s}_migrator set search_path = ${s};`);
  w(`alter role ${s}_migrator set role = ${s}_owner;`);
  w();
}

w(
  '-- Queues: one per consumer + its dead-letter queue (conventions §5) ------------------------------------------',
);
for (const c of consumers) {
  for (const q of [queueOf(c), `${queueOf(c)}_dlq`]) {
    w(
      `select pgmq.create(${lit(q)}) where not exists (select 1 from pgmq.list_queues() where queue_name = ${lit(q)});`,
    );
  }
}
w();

w(
  '-- Queue wrappers: the only way service roles touch pgmq (data-hosting §3). ---------------------------------',
);
w("-- Owned by the bootstrap role (SECURITY DEFINER), executable only by that service's runtime role.");
for (const svc of Object.keys(SERVICES)) {
  const s = schemaOf(svc);
  const own = queueOf(svc);
  const targets = sendTargets[svc];
  const consumes = consumers.includes(svc);
  w();
  w(`-- ${svc}: sends to ${targets.join(', ') || '(none)'}${consumes ? `; reads ${own}` : ''}`);
  w(
    `create or replace function ${s}.queue_send(p_queue text, p_msg jsonb, p_delay integer default 0) returns bigint`,
  );
  w("language plpgsql security definer set search_path = '' as $$");
  w('declare v_id bigint;');
  w('begin');
  w(`  if not (p_queue = any (array[${targets.map(lit).join(', ')}]::text[])) then`);
  w(`    raise exception 'queue % is not a consumer of ${svc} events', p_queue using errcode = '42501';`);
  w('  end if;');
  w('  select * into v_id from pgmq.send(p_queue, p_msg, p_delay);');
  w('  return v_id;');
  w('end $$;');
  const fns = [`${s}.queue_send(text, jsonb, integer)`];
  if (consumes) {
    w(
      `create or replace function ${s}.queue_read(p_vt integer, p_qty integer) returns setof pgmq.message_record`,
    );
    w(
      `language sql security definer set search_path = '' as $$ select * from pgmq.read(${lit(own)}, p_vt, p_qty) $$;`,
    );
    w(`create or replace function ${s}.queue_archive(p_msg_id bigint) returns boolean`);
    w(
      `language sql security definer set search_path = '' as $$ select pgmq.archive(${lit(own)}, p_msg_id) $$;`,
    );
    w(`create or replace function ${s}.queue_delete(p_msg_id bigint) returns boolean`);
    w(
      `language sql security definer set search_path = '' as $$ select pgmq.delete(${lit(own)}, p_msg_id) $$;`,
    );
    w(`create or replace function ${s}.queue_dead_letter(p_msg jsonb) returns bigint`);
    w(
      `language sql security definer set search_path = '' as $$ select * from pgmq.send(${lit(`${own}_dlq`)}, p_msg, 0) $$;`,
    );
    w(
      `create or replace function ${s}.queue_depths(out queue_name text, out queue_length bigint, out oldest_msg_age_sec integer)`,
    );
    w('returns setof record');
    w("language sql security definer set search_path = '' as $$");
    w(
      `  select m.queue_name, m.queue_length, m.oldest_msg_age_sec from pgmq.metrics_all() m where m.queue_name in (${lit(own)}, ${lit(`${own}_dlq`)})`,
    );
    w('$$;');
    fns.push(
      `${s}.queue_read(integer, integer)`,
      `${s}.queue_archive(bigint)`,
      `${s}.queue_delete(bigint)`,
      `${s}.queue_dead_letter(jsonb)`,
      `${s}.queue_depths()`,
    );
  }
  for (const f of fns) {
    w(`revoke all on function ${f} from public, anon, authenticated;`);
    w(`grant execute on function ${f} to ${s}_svc;`);
  }
}
w();

writeFileSync(
  new URL('infra/supabase/migrations/20260927000000_platform_bootstrap.sql', root),
  `${out.join('\n')}\n`,
);
process.stdout.write(
  `db bootstrap: ${Object.keys(SERVICES).length} services, ${consumers.length * 2} queues\n`,
);
