// ------------------------------------------------------------------------------------------ field builders
const vocab = (field: string, label: string, column: string, vocabulary = field): FieldSpec => ({
  field,
  label,
  shape: 'scalar',
  type: 'text',
  ops: SET_NULL,
  vocabulary,
  column,
});
const vocabArray = (field: string, label: string, column: string, vocabulary: string): FieldSpec => ({
  field,
  label,
  shape: 'array',
  type: 'text',
  ops: SET,
  vocabulary,
  column,
});
const enumField = (field: string, label: string, column: string, values: readonly string[]): FieldSpec => ({
  field,
  label,
  shape: 'scalar',
  type: 'text',
  ops: SET_NULL,
  values,
  column,
});
const range = (field: string, label: string, min: string, max: string, type: 'number' | 'inr' = 'number'): FieldSpec => ({
  field,
  label,
  shape: 'range',
  type,
  ops: field === 'bhk' || field.endsWith('area_sqft') ? NUM : RANGE,
  min,
  max,
});
const dateField = (field: string, label: string, column: string, type: 'date' | 'datetime'): FieldSpec => ({
  field,
  label,
  shape: 'scalar',
  type,
  ops: DATE,
  column,
});
const scalar = (field: string, label: string, column: string, type: FieldSpec['type'], ops: readonly Op[]): FieldSpec => ({
  field,
  label,
  shape: 'scalar',
  type,
  ops,
  column,
});
const group = (key: string, label: string, column: string, type: GroupSpec['type'] = 'string'): GroupSpec => ({
  key,
  label,
  column,
  type,
});

