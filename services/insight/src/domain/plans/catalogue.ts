export function templateOf(planId: string, version?: number): PlanTemplateDef | undefined {
  return CATALOGUE.find((t) => t.planId === planId && (version === undefined || t.version === version));
}

/** Data-plan templates the export and the Open-in-panel paths accept. */
export function isListTemplate(t: PlanTemplateDef): boolean {
  return t.kind === 'list';
}
